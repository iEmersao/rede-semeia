CREATE TABLE IF NOT EXISTS doador (
  id_doador INTEGER PRIMARY KEY AUTOINCREMENT,
  nome TEXT NOT NULL,
  email TEXT UNIQUE,
  telefone TEXT,
  data_cadastro TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS categoria (
  id_categoria INTEGER PRIMARY KEY AUTOINCREMENT,
  nome TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS item (
  id_item INTEGER PRIMARY KEY AUTOINCREMENT,
  id_categoria INTEGER NOT NULL REFERENCES categoria(id_categoria)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  nome TEXT NOT NULL,
  unidade TEXT NOT NULL DEFAULT 'unidade',
  UNIQUE (id_categoria, nome)
);

CREATE TABLE IF NOT EXISTS doacao (
  id_doacao INTEGER PRIMARY KEY AUTOINCREMENT,
  id_doador INTEGER NOT NULL REFERENCES doador(id_doador)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  data_doacao TEXT NOT NULL,
  observacao TEXT,
  criado_em TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS doacao_item (
  id_doacao INTEGER NOT NULL REFERENCES doacao(id_doacao)
    ON UPDATE CASCADE ON DELETE CASCADE,
  id_item INTEGER NOT NULL REFERENCES item(id_item)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  quantidade INTEGER NOT NULL CHECK (quantidade > 0),
  PRIMARY KEY (id_doacao, id_item)
);
